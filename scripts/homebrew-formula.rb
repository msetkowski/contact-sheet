#!/usr/bin/env ruby
# frozen_string_literal: true

# Prints the Homebrew formula for a release, for the tap at
# https://github.com/msetkowski/homebrew-tap.
#
# The formula installs the prebuilt binaries of the GitHub release; their
# SHA-256 checksums are read from the release's .sha256 files.
#
#   gh release download v1.2.3 --pattern '*.sha256' --dir checksums
#   ruby scripts/homebrew-formula.rb 1.2.3 checksums > Formula/contact-sheet.rb
#
# The release workflow runs this after each release and pushes the result to
# the tap.

REPO = 'https://github.com/msetkowski/contact-sheet'

# Homebrew platform block => release target.
TARGETS = {
  %w[macos arm] => 'aarch64-apple-darwin',
  %w[macos intel] => 'x86_64-apple-darwin',
  %w[linux arm] => 'aarch64-unknown-linux-musl',
  %w[linux intel] => 'x86_64-unknown-linux-musl'
}.freeze

version, checksum_dir = ARGV
abort("usage: #{$PROGRAM_NAME} VERSION CHECKSUM_DIR") unless version && checksum_dir
abort("invalid version: #{version}") unless version =~ /\A\d+\.\d+\.\d+\z/

def archive(version, target)
  "contact-sheet-v#{version}-#{target}.tar.gz"
end

def sha256(dir, file)
  path = File.join(dir, "#{file}.sha256")
  abort("missing #{path}") unless File.exist?(path)
  hash = File.read(path).split.first.to_s
  abort("no SHA-256 in #{path}") unless hash =~ /\A\h{64}\z/
  hash
end

def platform_block(os, version, checksum_dir)
  arches = TARGETS.select { |(target_os, _), _| target_os == os }
  inner = arches.map do |(_, arch), target|
    file = archive(version, target)
    <<-RUBY.chomp
    on_#{arch} do
      url "#{REPO}/releases/download/v#{version}/#{file}"
      sha256 "#{sha256(checksum_dir, file)}"
    end
    RUBY
  end
  "  on_#{os} do\n#{inner.join("\n")}\n  end"
end

puts <<~RUBY
  # Generated by scripts/homebrew-formula.rb in #{REPO}
  # and updated automatically after each release. Do not edit by hand.
  class ContactSheet < Formula
    desc "Create contact sheets (JPEG or PDF/X-4) from RAW, DNG, TIFF and JPEG photos"
    homepage "#{REPO}"
    license "Apache-2.0"

  #{platform_block('macos', version, checksum_dir)}

  #{platform_block('linux', version, checksum_dir)}

    def install
      bin.install "contact-sheet"
      # Licences of the font and the libraries built into the binary.
      prefix.install "LICENSE-DejaVu.txt", "THIRD-PARTY-LICENSES.txt"
    end

    test do
      assert_match "contact-sheet \#{version}", shell_output("\#{bin}/contact-sheet --version")

      # A folder without photos is reported as an error (exit status 1).
      (testpath/"photos").mkpath
      output = shell_output("\#{bin}/contact-sheet \#{testpath}/photos 2>&1", 1)
      assert_match "no supported files", output
    end
  end
RUBY
